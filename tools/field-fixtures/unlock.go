// unlock.json: the two JWS kinds an unlock key signs
// (docs/field-unlock-keys-spec.md section 3), for the device libraries to
// check their signer byte for byte, and the attestation challenge they set on
// an Android key. The platform's verifier (fieldauth.VerifyUnlockJWS) must
// accept every "valid" case and refuse every other one; main_test.go checks it.

const unlockDescription = "Unlock-key vectors (docs/field-unlock-keys-spec.md section 3; docs/wire-contract.md, Field identity, Unlock keys). " +
	"unlockKey is a fixed P-256 test key (public by design). Each case gives the JOSE header and claims a library builds, the exact " +
	"signingInput (base64url(header) '.' base64url(claims), with the members in the order shown), and a jws signed with the case's key " +
	"(raw r||s, deterministic). A library compares its signingInput with the vector's and verifies the vector's jws with the key's public half. " +
	"expect is \"valid\" or why the platform refuses it (every refusal is 401 INVALID_UNLOCK_PROOF on the wire). verifyWith names what the " +
	"platform expects: the nonce of a key proof is the registration request's DPoP nonce; the nonce of an assertion is the challenge. " +
	"attestationChallenge is SHA-256 of the UTF-8 string shown, the value a library passes to setAttestationChallenge. Generated by tools/field-fixtures; do not edit."

type unlockExpectJSON struct {
	Type     string `json:"type"`
	KeyID    string `json:"keyId,omitempty"`
	Aud      string `json:"aud"`
	Nonce    string `json:"nonce"`
	Sub      string `json:"sub"`
	DeviceID string `json:"deviceId"`
	App      string `json:"app,omitempty"`
}

type unlockCase struct {
	Name         string           `json:"name"`
	Kind         string           `json:"kind"` // keyProof | assertion
	Header       json.RawMessage  `json:"header"`
	Claims       json.RawMessage  `json:"claims"`
	SigningInput string           `json:"signingInput"`
	JWS          string           `json:"jws"`
	VerifyWith   unlockExpectJSON `json:"verifyWith"`
	Now          string           `json:"now"`
	Expect       string           `json:"expect"`
}

type unlockFile struct {
	Description          string            `json:"description"`
	BaseURL              string            `json:"baseUrl"`
	UnlockKey            map[string]string `json:"unlockKey"`
	UnlockKeyID          string            `json:"unlockKeyId"`
	WorkerID             string            `json:"workerId"`
	DeviceID             string            `json:"deviceId"`
	AppCode              string            `json:"appCode"`
	AttestationChallenge struct {
		Input string `json:"input"`
		Hex   string `json:"hex"`
	} `json:"attestationChallenge"`
	Cases []unlockCase `json:"cases"`
}

// orderedJSON marshals the members in the order given (a map would sort
// them), so the signing input is the one a library writing them in that order
// produces.
func orderedJSON(kv ...any) json.RawMessage {
	var b strings.Builder
	b.WriteByte('{')
	for i := 0; i+1 < len(kv); i += 2 {
		if i > 0 {
			b.WriteByte(',')
		}
		k, err := json.Marshal(kv[i])
		if err != nil {
			panic(err)
		}
		v, err := json.Marshal(kv[i+1])
		if err != nil {
			panic(err)
		}
		b.Write(k)
		b.WriteByte(':')
		b.Write(v)
	}
	b.WriteByte('}')
	return json.RawMessage(b.String())
}

func unlockFixtures() []byte {
	const (
		workerID = "fwu_0FIXTUREWORKER"
		deviceID = "fwd_0FIXTUREDEVICE"
		keyID    = "fwk_0FIXTUREUNLOCK"
		sid      = "fws_0FIXTUREFAMILY"
		nonce    = "fixture-dpop-nonce-0001"
		chal     = "fixture-unlock-challenge-0001"
	)
	key := newKey("fc-field-fixture-unlock-key")
	other := newKey("fc-field-fixture-other-unlock-key")
	iat := fixedNow.Unix()
	now := fixedNow.Format("2006-01-02T15:04:05Z")
	proofAud, unlockAud := issuer+"/field/auth/unlock-keys", issuer+"/field/auth/unlock"

	mk := func(name, kind, expect string, signer fixtureKey, header, claims json.RawMessage, want unlockExpectJSON) unlockCase {
		input := encodeRaw(header) + "." + encodeRaw(claims)
		return unlockCase{
			Name: name, Kind: kind, Header: header, Claims: claims, SigningInput: input,
			JWS: input + "." + encodeBytes(signer.sign(input)), VerifyWith: want, Now: now, Expect: expect,
		}
	}
	proofHeader := orderedJSON("typ", "fc-unlock-key+jwt", "alg", "ES256")
	proofClaims := orderedJSON("aud", proofAud, "nonce", nonce, "sub", workerID, "device_id", deviceID, "iat", iat)
	proofWant := unlockExpectJSON{Type: "fc-unlock-key+jwt", Aud: proofAud, Nonce: nonce, Sub: workerID, DeviceID: deviceID}
	asHeader := orderedJSON("typ", "fc-unlock+jwt", "alg", "ES256", "kid", keyID)
	asClaims := orderedJSON("aud", unlockAud, "nonce", chal, "sub", workerID, "device_id", deviceID, "app", appCode, "iat", iat)
	asWant := unlockExpectJSON{
		Type: "fc-unlock+jwt", KeyID: keyID, Aud: unlockAud, Nonce: chal, Sub: workerID,
		DeviceID: deviceID, App: appCode,
	}

	f := unlockFile{
		Description: unlockDescription, BaseURL: issuer, UnlockKey: key.jwkMap, UnlockKeyID: keyID,
		WorkerID: workerID, DeviceID: deviceID, AppCode: appCode,
		Cases: []unlockCase{
			mk("key_proof_valid", "keyProof", "valid", key, proofHeader, proofClaims, proofWant),
			mk("assertion_valid", "assertion", "valid", key, asHeader, asClaims, asWant),
			mk("assertion_signed_by_another_key", "assertion", "signature", other, asHeader, asClaims, asWant),
			mk("assertion_with_key_proof_typ", "assertion", "typ", key,
				orderedJSON("typ", "fc-unlock-key+jwt", "alg", "ES256", "kid", keyID), asClaims, asWant),
			mk("assertion_with_dpop_typ", "assertion", "typ", key,
				orderedJSON("typ", "dpop+jwt", "alg", "ES256", "kid", keyID), asClaims, asWant),
			mk("assertion_other_kid", "assertion", "kid", key,
				orderedJSON("typ", "fc-unlock+jwt", "alg", "ES256", "kid", "fwk_0SOMEOTHERKEY"), asClaims, asWant),
			mk("assertion_other_app", "assertion", "app", key, asHeader,
				orderedJSON("aud", unlockAud, "nonce", chal, "sub", workerID, "device_id", deviceID, "app", "other-app", "iat", iat), asWant),
			mk("assertion_key_proof_audience", "assertion", "aud", key, asHeader,
				orderedJSON("aud", proofAud, "nonce", chal, "sub", workerID, "device_id", deviceID, "app", appCode, "iat", iat), asWant),
			mk("key_proof_with_kid", "keyProof", "kid", key,
				orderedJSON("typ", "fc-unlock-key+jwt", "alg", "ES256", "kid", keyID), proofClaims, proofWant),
			mk("key_proof_other_nonce", "keyProof", "nonce", key, proofHeader,
				orderedJSON("aud", proofAud, "nonce", "some-other-nonce", "sub", workerID, "device_id", deviceID, "iat", iat), proofWant),
		},
	}
	f.AttestationChallenge.Input = "fc-unlock-key-attestation:v1\n" + sid + "\n" + workerID + "\n" + deviceID
	sum := sha256.Sum256([]byte(f.AttestationChallenge.Input))
	f.AttestationChallenge.Hex = hex.EncodeToString(sum[:])
	out, err := json.MarshalIndent(f, "", "  ")
	if err != nil {
		panic(err)
	}
	return append(out, '\n')
}

func encodeRaw(b json.RawMessage) string { return base64.RawURLEncoding.EncodeToString(b) }

func encodeBytes(b []byte) string { return base64.RawURLEncoding.EncodeToString(b) }
