// Error codes of the impersonation paths that the protocol layer maps to wire
// responses.
const (
	CodeInvalidSignInCode = "INVALID_CODE"
	CodeUnknownDevice     = "UNKNOWN_DEVICE"
	CodeNoAppAccess       = "NO_APP_ACCESS"
)

// PrincipalSignInCode is the execution-context principal of a sign-in code
// redemption: the caller is a device holding a code (the acting principal is
// in the event data), not a platform principal.
const PrincipalSignInCode = "field:sign-in-code"

// ── create a console sign-in code ────────────────────────────────────────

// CreateSignInCodeCommand mints a single-use code that signs a worker in to an
// application on whatever device redeems it. Code is generated by the caller
// with [NewSignInCodeValue]; it is never audited and only its hash is stored.
// The coarse permission (impersonate, or manage for a test identity) is the
// controller's; this operation client-boxes the worker and checks the target.
type CreateSignInCodeCommand struct {
	WorkerRef
	AppCode string `json:"appCode"`
	Code    string `json:"-"`
}

// CreateSignInCodeResult is what the admin needs back.
type CreateSignInCodeResult struct {
	CodeID    string
	WorkerID  string
	AppCode   string
	ExpiresAt time.Time
}

// CreateSignInCode creates a sign-in code for an ACTIVE worker granted the
// application.
func (o *Ops) CreateSignInCode() usecaseop.TxOperation[CreateSignInCodeCommand, CreateSignInCodeResult] {
	return usecaseop.TxOperation[CreateSignInCodeCommand, CreateSignInCodeResult]{
		Name: "CreateFieldSignInCode",
		Validate: func(ctx context.Context, cmd CreateSignInCodeCommand) error {
			if err := validateRef(ctx, cmd.WorkerRef); err != nil {
				return err
			}
			if strings.TrimSpace(cmd.AppCode) == "" {
				return usecase.Validation("APP_CODE_REQUIRED", "appCode is required")
			}
			if cmd.Code == "" {
				return usecase.Internal("CODE_MISSING", "sign-in code was not generated", nil)
			}
			return nil
		},
		Authorize: usecaseop.Public[CreateSignInCodeCommand],
		Execute: func(ctx context.Context, s *usecasepgx.TxScopedUnitOfWork, cmd CreateSignInCodeCommand, ec usecase.ExecutionContext) (CreateSignInCodeResult, error) {
			var zero CreateSignInCodeResult
			if strings.TrimSpace(ec.PrincipalID) == "" {
				return zero, usecase.Authorization("PRINCIPAL_REQUIRED", "a sign-in code is issued on behalf of a principal")
			}
			apps, err := o.resolveApps(ctx, []string{cmd.AppCode}, true)
			if err != nil {
				return zero, err
			}
			ident, err := o.loadWorker(ctx, cmd.ID, cmd.ClientID)
			if err != nil {
				return zero, err
			}
			if ident.Status != StatusActive {
				return zero, usecase.Conflict(CodeWorkerUnavailable, "the worker is not active")
			}
			if !ident.HasApp(apps[0].ID) {
				return zero, usecase.Conflict(CodeNoAppAccess, "the worker is not granted that application")
			}
			var creatorName string
			if err := s.WithTx(ctx, func(tx pgx.Tx) error {
				err := tx.QueryRow(ctx, `SELECT name FROM iam_principals WHERE id = $1`, ec.PrincipalID).Scan(&creatorName)
				if errors.Is(err, pgx.ErrNoRows) {
					return nil
				}
				return err
			}); err != nil {
				return zero, repoErr("find_principal", err)
			}
			now := time.Now().UTC()
			code := &SignInCode{
				ID: tsid.Generate(tsid.FieldSignInCode), ClientID: ident.ClientID, IdentityID: ident.ID,
				ApplicationID: apps[0].ID, CodeHash: HashBadgeToken(cmd.Code), CreatedBy: ec.PrincipalID,
				CreatedByName: creatorName, ExpiresAt: now.Add(SignInCodeTTL), CreatedAt: now,
			}
			ev := NewEvent(ec, WorkerSignInCodeCreatedType, "field-worker", ident.ID, workerData(ident, map[string]any{
				"appCode": apps[0].Code, "createdBy": ec.PrincipalID, "expiresAt": code.ExpiresAt.Format(time.RFC3339),
			}))
			if _, err := usecase.Into(usecasepgx.CommitScoped(ctx, s, code, o.R.SignIns, ev, cmd)); err != nil {
				return zero, err
			}
			return CreateSignInCodeResult{CodeID: code.ID, WorkerID: ident.ID, AppCode: apps[0].Code, ExpiresAt: code.ExpiresAt}, nil
		},
	}
}

// ── impersonation events ─────────────────────────────────────────────────

// ImpersonationInfo describes one impersonated sign-in, for the event.
type ImpersonationInfo struct {
	WorkerID  string `json:"workerId"`
	ClientID  string `json:"clientId"`
	AppCode   string `json:"appCode"`
	ActorType string `json:"actorType"`
	ActorID   string `json:"actorId"`
	// Method is ACT_AS or SIGN_IN_CODE.
	Method    string `json:"method"`
	DeviceID  string `json:"deviceId,omitempty"`
	SessionID string `json:"sessionId"`
}

func impersonatedEvent(ec usecase.ExecutionContext, in ImpersonationInfo, workerCode string) Event {
	data := map[string]any{
		"workerId": in.WorkerID, "clientId": in.ClientID, "workerCode": workerCode, "appCode": in.AppCode,
		"actorType": in.ActorType, "actorId": in.ActorID, "method": in.Method, "sessionId": in.SessionID,
	}
	if in.DeviceID != "" {
		data["deviceId"] = in.DeviceID
	}
	return NewEvent(ec, WorkerImpersonatedType, "field-worker", in.WorkerID, data)
}

// NoteImpersonated records that a supervisor signed in as a worker (act-as).
// The session itself was written by the protocol layer's AuthTx, with the
// supervisor's PIN accounting; this emits the event.
func (o *Ops) NoteImpersonated() usecaseop.TxOperation[ImpersonationInfo, struct{}] {
	return usecaseop.TxOperation[ImpersonationInfo, struct{}]{
		Name:      "NoteFieldImpersonated",
		Authorize: usecaseop.Public[ImpersonationInfo],
		Execute: func(ctx context.Context, s *usecasepgx.TxScopedUnitOfWork, cmd ImpersonationInfo, ec usecase.ExecutionContext) (struct{}, error) {
			var code string
			if err := s.WithTx(ctx, func(tx pgx.Tx) error {
				return tx.QueryRow(ctx, `SELECT worker_code FROM field_identities WHERE id = $1`, cmd.WorkerID).Scan(&code)
			}); err != nil {
				return struct{}{}, repoErr("find_field_worker", err)
			}
			_, err := usecase.Into(usecasepgx.EmitEventScoped(ctx, s, impersonatedEvent(ec, cmd, code), cmd))
			return struct{}{}, err
		},
	}
}

// ── redeem a console sign-in code ────────────────────────────────────────

// RedeemSignInCodeCommand signs a worker in with a console sign-in code. The
// protocol layer has verified the proof; Device is the enrolled device the
// proof key belongs to (nil on an unenrolled key). The refresh token is
// generated by the caller; only its hash comes in. Nothing here is audited.
type RedeemSignInCodeCommand struct {
	Code        string  `json:"-"`
	Device      *Device `json:"-"`
	JKT         string  `json:"jkt"`
	RefreshHash string  `json:"-"`
}

// RedeemedSignIn is a signed-in impersonated worker, ready for a token.
type RedeemedSignIn struct {
	Session   *Session
	Worker    *Identity
	Client    *client.Client
	App       *application.Application
	ActorName string
}

// RedeemSignInCode consumes the code and starts an impersonated session for
// its worker and application, in one transaction: a redemption that fails any
// check leaves the code unused. The errors are INVALID_CODE (unknown, used,
// expired, or its creator is no longer active), UNKNOWN_DEVICE (the client
// requires an enrolled device) and NO_APP_ACCESS (anything else).
func (o *Ops) RedeemSignInCode() usecaseop.TxOperation[RedeemSignInCodeCommand, RedeemedSignIn] {
	return usecaseop.TxOperation[RedeemSignInCodeCommand, RedeemedSignIn]{
		Name: "RedeemFieldSignInCode",
		Validate: func(_ context.Context, cmd RedeemSignInCodeCommand) error {
			if cmd.JKT == "" || cmd.RefreshHash == "" {
				return usecase.Internal("REDEEM_INVALID", "jkt and refresh hash are required", nil)
			}
			return nil
		},
		// The code is the credential; there is no principal.
		Authorize: usecaseop.Public[RedeemSignInCodeCommand],
		Execute: func(ctx context.Context, s *usecasepgx.TxScopedUnitOfWork, cmd RedeemSignInCodeCommand, ec usecase.ExecutionContext) (RedeemedSignIn, error) {
			var zero RedeemedSignIn
			invalid := usecase.Authorization(CodeInvalidSignInCode, "the sign-in code is invalid, used or expired")
			noAccess := usecase.Authorization(CodeNoAppAccess, "this worker cannot sign in to that application on this device")

			norm := NormalizeToken(cmd.Code)
			if !WellFormedToken(SignInCodePrefix, norm) {
				return zero, invalid
			}
			var code *SignInCode
			var creatorActive bool
			var creatorName string
			var ident *Identity
			if err := s.WithTx(ctx, func(tx pgx.Tx) error {
				var err error
				if code, err = o.R.SignIns.Consume(ctx, tx, HashToken(norm)); err != nil || code == nil {
					return err
				}
				err = tx.QueryRow(ctx, `SELECT active, name FROM iam_principals WHERE id = $1`, code.CreatedBy).
					Scan(&creatorActive, &creatorName)
				if errors.Is(err, pgx.ErrNoRows) {
					return nil
				}
				if err != nil {
					return err
				}
				ident, err = (&AuthTx{tx: tx}).LockIdentityByID(ctx, code.IdentityID)
				return err
			}); err != nil {
				return zero, repoErr("consume_sign_in_code", err)
			}
			if code == nil || !creatorActive {
				return zero, invalid
			}

			cl, err := o.Clients.FindByID(ctx, code.ClientID)
			if err != nil {
				return zero, repoErr("find_client", err)
			}
			pol, err := o.R.Policies.Effective(ctx, code.ClientID)
			if err != nil {
				return zero, repoErr("find_field_policy", err)
			}
			if cmd.Device == nil && pol.RequireEnrolledDevice {
				return zero, usecase.Authorization(CodeUnknownDevice, "this device is not enrolled")
			}
			app, err := o.Apps.FindByID(ctx, code.ApplicationID)
			if err != nil {
				return zero, repoErr("find_application", err)
			}
			switch {
			case cl == nil || cl.Status != client.StatusActive,
				ident == nil || ident.Status != StatusActive || ident.ClientID != code.ClientID,
				app == nil || !app.Active,
				!ident.HasApp(string(app.ID)),
				cmd.Device != nil && !cmd.Device.HasApp(string(app.ID)):
				return zero, noAccess
			}

			now := time.Now().UTC().Truncate(time.Microsecond)
			sess := NewSession(now, ident, string(app.ID), cmd.Device, cmd.JKT, cmd.RefreshHash, pol)
			sess.AMR = []string{"code", "imp"}
			sess.ActorType, sess.ActorID = ActorPrincipal, code.CreatedBy
			sess.CapAbsolute(now.Add(time.Duration(pol.ImpersonationMaxSecs) * time.Second))
			if err := s.WithTx(ctx, func(tx pgx.Tx) error {
				return (&AuthTx{tx: tx}).InsertSession(ctx, sess)
			}); err != nil {
				return zero, repoErr("insert_session", err)
			}
			info := ImpersonationInfo{
				WorkerID: ident.ID, ClientID: ident.ClientID, AppCode: app.Code, ActorType: ActorPrincipal,
				ActorID: code.CreatedBy, Method: MethodSignInCode, SessionID: sess.FamilyID,
			}
			if cmd.Device != nil {
				info.DeviceID = cmd.Device.ID
			}
			// The audit row reads "the creating principal impersonated the worker":
			// the execution-context principal is the actor, the entity the worker,
			// the audited command the impersonation (never the code).
			actorEC := usecase.NewExecutionContext(code.CreatedBy)
			if _, err := usecase.Into(usecasepgx.EmitEventScoped(ctx, s, impersonatedEvent(actorEC, info, ident.WorkerCode), info)); err != nil {
				return zero, err
			}
			return RedeemedSignIn{Session: sess, Worker: ident, Client: cl, App: app, ActorName: creatorName}, nil
		},
	}
}

// ActorOf resolves who is acting in an impersonated session for the act
// claim, and whether they still may: a supervisor must be ACTIVE and still
// canImpersonate, a principal must be active. ok is false when the actor can no
// longer act (the session must not be refreshed).
func (o *Ops) ActorOf(ctx context.Context, sess *Session) (name string, ok bool, err error) {
	switch sess.ActorType {
	case ActorFieldWorker:
		a, err := o.R.Identities.FindByID(ctx, sess.ActorID)
		if err != nil || a == nil {
			return "", false, err
		}
		return a.Name, a.Status == StatusActive && a.CanImpersonate, nil
	case ActorPrincipal:
		name, active, found, err := o.R.Sessions.PrincipalName(ctx, sess.ActorID)
		return name, found && active, err
	}
	return "", false, nil
}

// NewSession builds the first session of a login family for ident on the
// proof key: bound to the device when there is one (nil on an unenrolled key),
// limits from the policy. pcr and the actor are the caller's to set.
func NewSession(now time.Time, ident *Identity, appID string, dev *Device, jkt, refreshHash string, pol Policy) *Session {
	mode := ModePersonal
	deviceID := ""
	if dev != nil {
		mode, deviceID = dev.Mode, dev.ID
	}
	idle, absolute := pol.SessionLimits(mode, dev != nil)
	id := NewSessionID()
	return &Session{
		ID: id, FamilyID: id, IdentityID: ident.ID, DeviceID: deviceID, ApplicationID: appID,
		RefreshHash: refreshHash, AuthTime: now, IssuedAt: now,
		IdleExpiresAt: now.Add(idle), AbsoluteExpiresAt: now.Add(absolute), JKT: jkt,
	}
}

// CapAbsolute lowers the session's absolute expiry to at most limit.
func (s *Session) CapAbsolute(limit time.Time) {
	if limit.Before(s.AbsoluteExpiresAt) {
		s.AbsoluteExpiresAt = limit
	}
}
