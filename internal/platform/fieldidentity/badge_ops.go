// Badge tokens and sign-in codes (docs/field-worker-sign-in-options-spec.md
// sections 3.1 and 4.2): a four-character type prefix and 26 Crockford base32
// characters (130 random bits), upper case. Upper-case alphanumerics use the
// QR alphanumeric mode and type correctly through a scanner's keyboard wedge.
const (
	BadgeTokenPrefix  = "FWB1"
	SignInCodePrefix  = "FWS1"
	tokenBodyLen      = 26
	crockfordAlphabet = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"

	// MaxBulkBadges bounds one bulk issue.
	MaxBulkBadges = 200
	// SignInCodeTTL is how long a console sign-in code stays valid.
	SignInCodeTTL = 10 * time.Minute

	maxBadgeLabelLen = 255
)

func newPrefixedToken(prefix string) (string, error) {
	var raw [tokenBodyLen]byte
	if _, err := rand.Read(raw[:]); err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString(prefix)
	for _, v := range raw {
		b.WriteByte(crockfordAlphabet[v&31]) // 256 % 32 == 0: uniform
	}
	return b.String(), nil
}

// NewBadgeToken returns a fresh badge token (shown once, at issue).
func NewBadgeToken() (string, error) { return newPrefixedToken(BadgeTokenPrefix) }

// NewSignInCodeValue returns a fresh console sign-in code.
func NewSignInCodeValue() (string, error) { return newPrefixedToken(SignInCodePrefix) }

// NormalizeToken upper-cases and trims a scanned or typed badge token or
// sign-in code (tokens compare case-insensitively).
func NormalizeToken(token string) string { return strings.ToUpper(strings.TrimSpace(token)) }

// WellFormedToken reports whether a normalised token has the shape of a token
// with the prefix. A malformed value cannot be a real one, so callers treat it
// as unknown without a lookup.
func WellFormedToken(prefix, token string) bool {
	if len(token) != len(prefix)+tokenBodyLen || !strings.HasPrefix(token, prefix) {
		return false
	}
	for _, c := range token[len(prefix):] {
		if !strings.ContainsRune(crockfordAlphabet, c) {
			return false
		}
	}
	return true
}

// HashBadgeToken is the stored form of a badge token or sign-in code.
func HashBadgeToken(token string) string { return HashToken(NormalizeToken(token)) }

// ── issue ────────────────────────────────────────────────────────────────

// IssueBadgeCommand mints a badge for one worker. Token is generated by the
// caller with [NewBadgeToken]; it is never audited and only its hash is stored.
type IssueBadgeCommand struct {
	WorkerRef
	Label string `json:"label,omitempty"`
	Token string `json:"-"`
}

// IssuedBadge is one issued badge with its worker.
type IssuedBadge struct {
	Worker *Identity
	Badge  *Badge
}

func validateLabel(label string) error {
	if len(label) > maxBadgeLabelLen {
		return usecase.Validation("LABEL_TOO_LONG", "label is at most 255 characters")
	}
	return nil
}

// IssueBadge issues a new badge for a worker and, in the same transaction,
// revokes the worker's earlier ACTIVE badges (one active badge per worker).
func (o *Ops) IssueBadge() usecaseop.TxOperation[IssueBadgeCommand, IssuedBadge] {
	return usecaseop.TxOperation[IssueBadgeCommand, IssuedBadge]{
		Name: "IssueFieldBadge",
		Validate: func(ctx context.Context, cmd IssueBadgeCommand) error {
			if err := validateRef(ctx, cmd.WorkerRef); err != nil {
				return err
			}
			if cmd.Token == "" {
				return usecase.Internal("TOKEN_MISSING", "badge token was not generated", nil)
			}
			return validateLabel(cmd.Label)
		},
		Authorize: usecaseop.Public[IssueBadgeCommand],
		Execute: func(ctx context.Context, s *usecasepgx.TxScopedUnitOfWork, cmd IssueBadgeCommand, ec usecase.ExecutionContext) (IssuedBadge, error) {
			var zero IssuedBadge
			ident, err := o.loadWorker(ctx, cmd.ID, cmd.ClientID)
			if err != nil {
				return zero, err
			}
			b, err := o.issueBadge(ctx, s, ident, cmd.Label, cmd.Token, ec, cmd)
			if err != nil {
				return zero, err
			}
			return IssuedBadge{Worker: ident, Badge: b}, nil
		},
	}
}

func (o *Ops) issueBadge(ctx context.Context, s *usecasepgx.TxScopedUnitOfWork, ident *Identity,
	label, token string, ec usecase.ExecutionContext, cmd any,
) (*Badge, error) {
	now := time.Now().UTC()
	var revoked []string
	if err := s.WithTx(ctx, func(tx pgx.Tx) error {
		// Serialise concurrent issues for the worker, so the one-ACTIVE-badge
		// rule holds (the partial unique index is the backstop).
		if _, err := tx.Exec(ctx, `SELECT 1 FROM field_identities WHERE id = $1 FOR UPDATE`, ident.ID); err != nil {
			return err
		}
		var err error
		revoked, err = o.R.Badges.RevokeActive(ctx, tx, ident.ID, now)
		return err
	}); err != nil {
		return nil, repoErr("revoke_badges", err)
	}
	b := &Badge{
		ID: tsid.Generate(tsid.FieldBadge), ClientID: ident.ClientID, IdentityID: ident.ID,
		TokenHash: HashBadgeToken(token), Label: strings.TrimSpace(label), Status: BadgeActive,
		CreatedBy: ec.PrincipalID, CreatedAt: now,
	}
	ev := NewEvent(ec, WorkerBadgeIssuedType, "field-worker", ident.ID,
		workerData(ident, map[string]any{"badgeId": b.ID, "revokedBadgeIds": revoked}))
	if _, err := usecase.Into(usecasepgx.CommitScoped(ctx, s, b, o.R.Badges, ev, cmd)); err != nil {
		return nil, err
	}
	return b, nil
}

// IssueBadgesCommand mints one badge per worker (a sheet to print). Tokens[i]
// belongs to WorkerIDs[i]; they are never audited.
type IssueBadgesCommand struct {
	ClientID  string   `json:"clientId,omitempty"`
	WorkerIDs []string `json:"workerIds"`
	Tokens    []string `json:"-"`
}

// IssueBadges issues a badge for each worker in one transaction: every worker
// is loaded and client-boxed first, so a worker the caller cannot reach (or
// that does not exist) fails the whole batch and nothing is issued.
func (o *Ops) IssueBadges() usecaseop.TxOperation[IssueBadgesCommand, []IssuedBadge] {
	return usecaseop.TxOperation[IssueBadgesCommand, []IssuedBadge]{
		Name: "IssueFieldBadges",
		Validate: func(_ context.Context, cmd IssueBadgesCommand) error {
			if len(cmd.WorkerIDs) == 0 || len(cmd.WorkerIDs) > MaxBulkBadges {
				return usecase.Validation("WORKER_IDS_INVALID", "workerIds must name 1 to 200 workers")
			}
			if len(cmd.Tokens) != len(cmd.WorkerIDs) {
				return usecase.Internal("TOKEN_MISSING", "badge tokens were not generated", nil)
			}
			seen := make(map[string]bool, len(cmd.WorkerIDs))
			for _, id := range cmd.WorkerIDs {
				if strings.TrimSpace(id) == "" || seen[id] {
					return usecase.Validation("WORKER_IDS_INVALID", "workerIds must be distinct, non-empty ids")
				}
				seen[id] = true
			}
			return nil
		},
		Authorize: usecaseop.Public[IssueBadgesCommand],
		Execute: func(ctx context.Context, s *usecasepgx.TxScopedUnitOfWork, cmd IssueBadgesCommand, ec usecase.ExecutionContext) ([]IssuedBadge, error) {
			idents := make([]*Identity, 0, len(cmd.WorkerIDs))
			for _, id := range cmd.WorkerIDs {
				ident, err := o.loadWorker(ctx, id, cmd.ClientID)
				if err != nil {
					return nil, err
				}
				idents = append(idents, ident)
			}
			out := make([]IssuedBadge, 0, len(idents))
			for n, ident := range idents {
				b, err := o.issueBadge(ctx, s, ident, "", cmd.Tokens[n], ec, cmd)
				if err != nil {
					return nil, err
				}
				out = append(out, IssuedBadge{Worker: ident, Badge: b})
			}
			return out, nil
		},
	}
}

// ── revoke ───────────────────────────────────────────────────────────────

// BadgeRef addresses one badge of a worker.
type BadgeRef struct {
	WorkerRef
	BadgeID string `json:"badgeId"`
}

// RevokeBadge revokes a badge (terminal). Revoking an already-revoked badge is
// a no-op.
func (o *Ops) RevokeBadge() usecaseop.TxOperation[BadgeRef, Event] {
	return usecaseop.TxOperation[BadgeRef, Event]{
		Name: "RevokeFieldBadge",
		Validate: func(ctx context.Context, cmd BadgeRef) error {
			if err := validateRef(ctx, cmd.WorkerRef); err != nil {
				return err
			}
			if strings.TrimSpace(cmd.BadgeID) == "" {
				return usecase.Validation("BADGE_ID_REQUIRED", "badgeId is required")
			}
			return nil
		},
		Authorize: usecaseop.Public[BadgeRef],
		Execute: func(ctx context.Context, s *usecasepgx.TxScopedUnitOfWork, cmd BadgeRef, ec usecase.ExecutionContext) (Event, error) {
			ident, err := o.loadWorker(ctx, cmd.ID, cmd.ClientID)
			if err != nil {
				return Event{}, err
			}
			b, err := o.R.Badges.FindByID(ctx, cmd.BadgeID)
			if err != nil {
				return Event{}, repoErr("find_field_badge", err)
			}
			if b == nil || b.IdentityID != ident.ID {
				return Event{}, httperror.NotFound("FieldBadge", cmd.BadgeID)
			}
			if b.Status == BadgeRevoked {
				return Event{}, nil
			}
			now := time.Now().UTC()
			b.Status, b.RevokedAt = BadgeRevoked, &now
			ev := NewEvent(ec, WorkerBadgeRevokedType, "field-worker", ident.ID,
				workerData(ident, map[string]any{"badgeId": b.ID}))
			return usecase.Into(usecasepgx.CommitScoped(ctx, s, b, o.R.Badges, ev, cmd))
		},
	}
}
